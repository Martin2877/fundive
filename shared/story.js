// 取本宇宙的剧情：storyVar 0 用原版，1/2 用变体（没有变体的图回落原版）
export function storyOf(mapId, uni) {
  const base = STORY[mapId];
  if (!base) return null;
  const vars = STORY_VARS[mapId] || [];
  const v = uni && uni.storyVar ? vars[(uni.storyVar - 1) % vars.length] : null;
  if (!v) return base;
  return {
    ...base,
    briefing: v.briefing || base.briefing,
    epilogue: { ...base.epilogue, ...(v.epilogue || {}) },
  };
}

